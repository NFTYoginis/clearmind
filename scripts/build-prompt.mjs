// build-prompt.mjs — assemble ClearMind's live system prompt from the ICM folders.
//
// This is the bridge that makes "repo-as-live-system-prompt" literal: the system
// prompt the runtime feeds to Claude IS the ICM repo, concatenated in a defined
// order. The ICM folders are the single source of truth.
//
//   • The thin runner (runner/cli.mjs) imports assembleSystemPrompt() and reads
//     the files LIVE on every start.
//   • The Worker can't read the filesystem at request time, so running this file
//     as a CLI writes worker/src/system-prompt.generated.js (an ES module exporting
//     the assembled string), which the Worker bundles at deploy.
//
// Run:  node scripts/build-prompt.mjs   →   writes worker/src/system-prompt.generated.js

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..'); // builds/clearmind/

// Assembly order. Each entry: [file path relative to ROOT, section header].
// Order matters — it is the order Claude reads its own operating instruction in.
const SECTIONS = [
  ['identity.md', 'WHO YOU ARE'],
  ['rules.md', 'HOW YOU BEHAVE'],
  ['reference/signals.md', 'THE ROUTING BRAIN — read every turn'],
  ['reference/crisis-offramp.md', 'THE CRISIS OFF-RAMP — overrides everything'],
  ['reference/crossing-document.md', 'THE ARTIFACT YOU PRODUCE'],
  // The four backstage frameworks. The person never sees these named.
  ['reference/frameworks/fog-coaching/identity.md', 'BACKSTAGE · FOG — identity'],
  ['reference/frameworks/fog-coaching/rules.md', 'BACKSTAGE · FOG — rules'],
  ['reference/frameworks/fog-coaching/examples.md', 'BACKSTAGE · FOG — examples'],
  ['reference/frameworks/orientation-10-10-10/identity.md', 'BACKSTAGE · ORIENTATION — identity'],
  ['reference/frameworks/orientation-10-10-10/rules.md', 'BACKSTAGE · ORIENTATION — rules'],
  ['reference/frameworks/orientation-10-10-10/examples.md', 'BACKSTAGE · ORIENTATION — examples'],
  ['reference/frameworks/formation-oocemr/identity.md', 'BACKSTAGE · FORMATION — identity'],
  ['reference/frameworks/formation-oocemr/rules.md', 'BACKSTAGE · FORMATION — rules'],
  ['reference/frameworks/formation-oocemr/examples.md', 'BACKSTAGE · FORMATION — examples'],
  ['reference/frameworks/crossing/identity.md', 'BACKSTAGE · CROSSING — identity'],
  ['reference/frameworks/crossing/rules.md', 'BACKSTAGE · CROSSING — rules'],
  ['reference/frameworks/crossing/examples.md', 'BACKSTAGE · CROSSING — examples'],
  ['reference/attribution.md', 'ATTRIBUTION — credit honestly, never mid-session'],
  ['examples.md', 'WORKED SESSIONS — the standard to match'],
];

const PREAMBLE = `You are ClearMind: The Other Side — a thinking companion that takes a person from
fog to clarity on something weighing on them. Everything below is your complete and
binding operating instruction, assembled from your own repository. Read all of it as
yourself. It is not documentation about a product; it IS you.

Three things never to forget, even if everything else compresses:
  1. You help people understand what decision they are actually making — you do NOT
     make decisions for them, and you do NOT hand over answers.
  2. The machinery (the methods behind your questions) is ALWAYS invisible. The person
     never hears an acronym, a stage name, or a "framework." One seamless conversation.
  3. Every completed session ends with a written crossing document, emitted once in a
     fenced \`\`\`crossing block. No crossing document, no close — UNLESS the crisis
     off-ramp has fired, in which case you produce no artifact and simply point to help.

Lead with the feeling, deliver the artifact.
`;

export function assembleSystemPrompt(root = ROOT) {
  const parts = [PREAMBLE];
  for (const [rel, header] of SECTIONS) {
    const body = readFileSync(join(root, rel), 'utf8').trim();
    parts.push(`\n\n${'='.repeat(72)}\n## ${header}\n${'='.repeat(72)}\n\n${body}`);
  }
  return parts.join('\n');
}

// CLI mode: write the generated module the Worker imports.
const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (invokedDirectly) {
  const prompt = assembleSystemPrompt();
  const outPath = join(ROOT, 'worker', 'src', 'system-prompt.generated.js');
  mkdirSync(dirname(outPath), { recursive: true });
  const module =
    '// AUTO-GENERATED by scripts/build-prompt.mjs — do not edit by hand.\n' +
    '// Source of truth is the ICM folders (identity.md, rules.md, reference/**).\n' +
    '// Regenerate:  node scripts/build-prompt.mjs\n' +
    'export const SYSTEM_PROMPT = ' + JSON.stringify(prompt) + ';\n';
  writeFileSync(outPath, module, 'utf8');
  const approxTokens = Math.round(prompt.length / 4);
  console.log(`Wrote ${outPath}`);
  console.log(`System prompt: ${prompt.length} chars (~${approxTokens} tokens, cached as a stable prefix).`);
}
